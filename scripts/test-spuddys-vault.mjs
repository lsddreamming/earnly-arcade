import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { PGlite } from '@electric-sql/pglite';

const db = new PGlite();
const player = '00000000-0000-4000-8000-000000000001';
const other = '00000000-0000-4000-8000-000000000002';
let sequence = 0;
const id = () => '10000000-0000-4000-8000-' + String(++sequence).padStart(12,'0');
const run = async (actor, action, request = null, pack = null) =>
  (await db.query('select public.spuddy_vault_action($1,$2,$3,$4) as result',[actor,action,request,pack])).rows[0].result;
await db.exec(await readFile(new URL('../tests/commerce-fixture.sql',import.meta.url),'utf8'));
await db.exec(`
  create role service_role bypassrls;
  alter table auth.users add column is_anonymous boolean default false,
    add column email_confirmed_at timestamptz default now(), add column deleted_at timestamptz;
  create schema earnly_world;
  create table earnly_world.social_members(user_id uuid, suspended_until timestamptz);
  create table earnly_world.arcade_challenge_awards(user_id uuid, week date);
  grant usage on schema auth, earnly_world to service_role;
  grant select on auth.users, leaderboard_bans, earnly_world.social_members, earnly_world.arcade_challenge_awards to service_role;
  grant select,update on coin_wallets to service_role;
`);
await db.exec(await readFile(new URL('../supabase/migrations/20261106213000_spuddys_vault.sql',import.meta.url),'utf8'));
await db.exec('set role authenticated');
await assert.rejects(run(player,'status'),/permission denied/);
await db.exec('reset role; set role service_role');
const catalog = (await run(player,'status')).catalog;
for (const tier of ['starter','deluxe']) assert.equal(catalog.reduce((sum,card) => sum+card[tier],0),10000);
const key = id();
let result = await run(player,'buy',key,'deluxe');
assert.equal(result.balance,'950');
assert.equal(result.pending.card,null);
assert.equal((await run(player,'buy',key,'deluxe')).balance,'950');
assert.match((await run(player,'buy',id(),'starter')).error,/Finish/);
assert.match((await run(other,'reveal',key)).error,/not found/);
assert.match((await run(player,'sell',key)).error,/Reveal/);
result = await run(player,'reveal',key);
const card = result.pending.card;
assert.ok(catalog.find(entry => entry.id===card).deluxe);
assert.match((await run(player,'sell',key)).error,/first copy/);
assert.equal((await run(player,'vault',key)).owned[card],1);
assert.equal((await run(player,'vault',key)).owned[card],1);
await db.exec('reset role');
const duplicate = id();
await db.query("insert into earnly_world.spuddy_pulls values($1,$2,'deluxe',$3,50,null,true,null)",[player,duplicate,card]);
await db.query('update coin_wallets set balance=0 where user_id=$1',[player]);
await db.query("insert into earnly_world.arcade_challenge_awards values($1,date_trunc('week',now() at time zone 'UTC')::date)",[player]);
await db.exec('set role service_role');
assert.equal((await run(player,'sell',duplicate)).balance,'50');
assert.equal((await run(player,'sell',duplicate)).balance,'50');
assert.match((await run(player,'buy',id(),'deluxe')).error,/more Arcade Coins/);
const free = id();
assert.equal((await run(player,'buy',free,'weekly')).balance,'50');
await run(player,'reveal',free);
await run(player,'vault',free);
assert.match((await run(player,'buy',id(),'weekly')).error,/No weekly pack/);
await db.close();
console.log('PASS: odds, server-owned reveal, cross-account isolation, retry-safe charges and sales, weekly eligibility, insufficient balance.');
