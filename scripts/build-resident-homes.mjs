import {readFile,writeFile} from 'node:fs/promises';
import {RESIDENT_HOMES} from '../world-server/src/resident-homes.ts';
const q=s=>"'"+String(s).replaceAll("'","''")+"'";
const definitions=[...new Set(RESIDENT_HOMES.flatMap(h=>h.items.map(i=>i.definitionId)))];
const mapping=RESIDENT_HOMES.map(h=>`(${q(h.residentId)},${q(h.roomId)}::uuid)`).join(',\n');
const sql=`-- Generated by scripts/build-resident-homes.mjs. System scenery: no wallet, inventory or player-room writes.
do $$ begin
 if (select count(*) from earnly_world.item_definitions where id in (${definitions.map(q).join(',')})) <> ${definitions.length} then
  raise exception 'Resident home catalog definitions are missing';
 end if;
 if exists(select 1 from earnly_world.rooms where id in (${RESIDENT_HOMES.map(h=>q(h.roomId)+'::uuid').join(',')}) and owner_id is not null) then
  raise exception 'Resident home identity conflicts with a player room';
 end if;
end $$;
${RESIDENT_HOMES.map(h=>`insert into earnly_world.rooms(id,name,heightmap,access_type,max_users,public_items)
select ${q(h.roomId)}::uuid,${q(h.name)},${q(Array(h.size).fill('0'.repeat(h.size)).join('\n'))},'open',20,
 jsonb_agg(jsonb_build_object('id',p.item->>'id','definitionId',d.id,'name',d.name,'sprite',d.sprite_id,'color',d.color,'x',(p.item->>'x')::int,'y',(p.item->>'y')::int,'z',0,'width',d.width,'length',d.length,'rotation',0,'itemHeight',d.item_height,'walkable',d.walkable,'canStack',d.can_stack,'canSit',d.can_sit,'canLay',d.can_lay) order by p.ord)
from jsonb_array_elements(${q(JSON.stringify(h.items))}::jsonb) with ordinality p(item,ord)
join earnly_world.item_definitions d on d.id=p.item->>'definitionId'
on conflict(id) do nothing;`).join('\n')}

-- Only public system-room facts; no player records or private memories.
create or replace function public.world_resident_home_catalog() returns jsonb
language sql stable security invoker set search_path='' as $$
 with homes(resident_id,room_id) as (values ${mapping})
 select coalesce(jsonb_agg(jsonb_build_object('residentId',h.resident_id,'roomId',r.id,'name',r.name,
 'items',(select jsonb_agg(i->>'name') from jsonb_array_elements(r.public_items) i),
 'animatedFish',exists(select 1 from jsonb_array_elements(r.public_items) i where i->>'sprite'='show-aquarium')) order by h.resident_id),'[]'::jsonb)
 from homes h join earnly_world.rooms r on r.id=h.room_id where r.owner_id is null and r.access_type='open';
$$;
revoke all on function public.world_resident_home_catalog() from public,anon,authenticated;
grant execute on function public.world_resident_home_catalog() to service_role;
`;
const path=new URL('../supabase/migrations/20261029191500_world_resident_homes.sql',import.meta.url);
if(process.argv.includes('--check')){if(await readFile(path,'utf8')!==sql)throw new Error('Regenerate resident home migration');}else await writeFile(path,sql);
